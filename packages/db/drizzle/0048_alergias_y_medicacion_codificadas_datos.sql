-- de la lista; lo demás queda «sin codificar» y se elige después.

-- 1. Lo que un clínico descartó antes del cambio queda como quitada porque «era
-- otra cosa» (FHIR refuted). Lo archivado sin motivo queda quitado, sin motivo.
UPDATE public.patient_allergy SET is_active = false, removed_reason = 'otra_cosa', removed_at = updated_at
WHERE verification = 'descartada' AND removed_reason IS NULL;--> statement-breakpoint
UPDATE public.patient_allergy SET removed_at = updated_at WHERE NOT is_active AND removed_at IS NULL;--> statement-breakpoint

-- 2. Sin nadie del equipo que la registrara, la dijo el paciente al registrarse.
UPDATE public.patient_allergy SET source = 'paciente' WHERE created_by IS NULL;--> statement-breakpoint

