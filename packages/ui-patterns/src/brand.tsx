const BRACKETS = "M16 10H6V102H16M112 10H122V102H112"

/** El isotipo: el número de la marca entre corchetes, en su caja de 128 × 112. */
function Isotype({ brand }: { brand: BrandId }) {
  return (
    <g>
      <g transform="translate(20 12) scale(.8)">
        {BRAND_DIGITS[brand].map((d) => (
          <path key={d} d={d} />
        ))}
      </g>
      <path d={BRACKETS} fill="none" stroke="currentColor" strokeWidth="5" />
    </g>
  )
}

/** El logotipo de la marca de esta app (`BrandProvider`), o el de `brand`; `compact` deja solo el isotipo. */
export function Brand({
  compact = false,
  className = "",
  brand,
}: {
  compact?: boolean
  className?: string
  brand?: BrandId
}) {
  const current = useBrand()
  const id = brand ?? current
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox={compact ? "0 0 128 112" : "-2 -10 597.2378223495703 134"}
      role="img"
      aria-label={BRAND_NAMES[id]}
      className={
        (compact ? "block h-8 w-9 shrink-0 " : "block h-auto w-40 max-w-full shrink-0 ") + className
      }
      style={{ color: "var(--identity-accent)" }}
      fill="currentColor"
    >
      {compact ? (
        <Isotype brand={id} />
      ) : (
        <>
          <g fill="var(--identity-ink)">
            {WORDMARKS[id].ink.map((d) => (
              <path key={d} d={d} />
            ))}
          </g>
          <g>
            {WORDMARKS[id].accent.map((d) => (
              <path key={d} d={d} />
            ))}
          </g>
          <g transform="translate(435.2378223495702 -13) scale(1.22)">
            <Isotype brand={id} />
          </g>
        </>
      )}
    </svg>
  )
}
